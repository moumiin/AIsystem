function createSign(curls) {
  const result = OPEN_PALM.map(([x, y, z]) => [x, y, z]);
  for (const [finger, curl] of Object.entries(curls)) {
    for (const idx of FINGER_INDICES[finger]) {
      const a = OPEN_PALM[idx], b = CLOSED_FIST[idx];
      result[idx] = [
        a[0] + (b[0] - a[0]) * curl,
        a[1] + (b[1] - a[1]) * curl,
        a[2] + (b[2] - a[2]) * curl,
      ];
    }
  }
  return result;
}

