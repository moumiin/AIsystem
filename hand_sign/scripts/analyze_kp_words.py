# 카테고리 매칭
categorized = {}
uncategorized = []

for word in sorted(kp):
    # 깨진 문자 제외
    if any(ord(c) > 0xD7A3 and ord(c) < 0xF900 for c in word):
        continue
    if re.search(r'[^가-힣0-9A-Za-z\s]', word):
        continue

    # 주소성 단어 제외 (너무 구체적인 서울 지명)
    if EXCLUDE.search(word):
        continue

    # 숫자만 있는 것 (1~12)
    if re.match(r'^\d+$', word) and int(word) <= 12:
        categorized.setdefault('numbers', []).append(word)
        continue

    # 카테고리 힌트 매칭
    matched = False
    for cat, hints in CATEGORY_HINTS.items():
        for hint in hints:
            if hint in word:
                categorized.setdefault(cat, []).append(word)
                matched = True
                break
        if matched:
            break

    if not matched:
        uncategorized.append(word)

print("=== 카테고리별 분류 결과 ===")
for cat, words in categorized.items():
    print(f"\n[{cat}] {len(words)}개:")
    print("  " + ", ".join(sorted(words)))

